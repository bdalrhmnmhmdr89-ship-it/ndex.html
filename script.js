function shuffle(a) {
  const b = a.slice();
  for (let i = b.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [b[i], b[j]] = [b[j], b[i]];
  }
  return b;
}

let S = null;      // { name, order, res, done }
let locked = false;

function save() { try { localStorage.setItem(KEY, JSON.stringify(S)); } catch (e) {} }
function wipe() { try { localStorage.removeItem(KEY); } catch (e) {} }
function load() {
  try {
    const r = localStorage.getItem(KEY);
    if (!r) return null;
    const s = JSON.parse(r);
    if (s && typeof s.name === 'string' && Array.isArray(s.order) && s.order.length === TOTAL &&
        Array.isArray(s.res) && s.res.length === s.done && s.done <= TOTAL) return s;
  } catch (e) {}
  return null;
}

function show(id) {
  ['start', 'quiz', 'result'].forEach(s => { $(s).hidden = s !== id; });
  $('brand').hidden = id === 'start';
  try { window.scrollTo(0, 0); } catch (e) {}
}

function el(tag, cls, text) {
  const x = document.createElement(tag);
  if (cls) x.className = cls;
  if (text !== undefined) x.textContent = text;
  return x;
}

