function score() { return S.res.reduce((a, b) => a + b, 0); }

function renderQuestion() {
  const pos = S.done;
  const q = QS[S.order[pos]];
  locked = false;
  $('qCount').textContent = 'السؤال ' + n(pos + 1) + ' من ' + n(TOTAL);
  $('scoreLive').textContent = 'الصحيح حتى الآن: ' + n(score());
  $('bar').style.width = (pos / TOTAL * 100) + '%';
  $('barWrap').setAttribute('aria-valuenow', String(pos));
  $('qCat').textContent = CATS[q.c];
  $('qText').textContent = q.q;
  const box = $('opts');
  box.replaceChildren();
  shuffle(q.opts).forEach((t, i) => {
    const b = el('button', 'opt');
    b.type = 'button';
    b.dataset.t = t;
    b.append(el('span', 'mark', LET[i]), el('span', 'txt', t));
    b.addEventListener('click', () => answer(b, q));
    box.append(b);
  });
  $('fb').hidden = true;
  $('nextBtn').hidden = true;
}

function answer(btn, q) {
  if (locked) return;
  locked = true;
  const ok = btn.dataset.t === q.a;
  S.res.push(ok ? 1 : 0);
  S.done = S.res.length;
  save();

  document.querySelectorAll('.opt').forEach(o => {
    o.disabled = true;
    if (o.dataset.t === q.a) { o.classList.add('correct'); o.querySelector('.mark').textContent = '✓'; }
  });
  if (!ok) { btn.classList.add('wrong'); btn.querySelector('.mark').textContent = '✕'; }

  const fb = $('fb');
  fb.replaceChildren();
  fb.className = 'fb ' + (ok ? 'ok' : 'no');
  fb.append(el('strong', '', ok ? 'إجابة صحيحة، أحسنت.' : 'إجابة غير صحيحة.'));
  if (!ok) {
    const r = el('p', 'right');
    r.append('الإجابة الصحيحة: ', el('b', '', q.a));
    fb.append(r);
  }
  fb.append(el('p', 'why', q.e));
  fb.hidden = false;

  $('scoreLive').textContent = 'الصحيح حتى الآن: ' + n(score());
  $('bar').style.width = (S.done / TOTAL * 100) + '%';
  $('barWrap').setAttribute('aria-valuenow', String(S.done));

  const nb = $('nextBtn');
  nb.textContent = S.done >= TOTAL ? 'عرض الشهادة' : 'السؤال التالي';
  nb.hidden = false;
  try { nb.scrollIntoView({ block: 'nearest', behavior: 'smooth' }); } catch (e) {}
}

