function star8(ctx, cx, cy, r) {
  const ri = r * 0.765;
  ctx.beginPath();
  for (let i = 0; i < 16; i++) {
    const a = i * Math.PI / 8 - Math.PI / 2;
    const rr = i % 2 ? ri : r;
    const x = cx + rr * Math.cos(a), y = cy + rr * Math.sin(a);
    if (i) ctx.lineTo(x, y); else ctx.moveTo(x, y);
  }
  ctx.closePath();
}

function levelOf(p) {
  if (p >= 0.9) return 'ممتاز';
  if (p >= 0.75) return 'جيد جدًا';
  if (p >= 0.6) return 'جيد';
  return 'مقبول';
}

async function drawCertificate(name, sc, total) {
  const D = 'Amiri, "Noto Naskh Arabic", "Traditional Arabic", serif';
  const B = '"IBM Plex Sans Arabic", "Segoe UI", Tahoma, sans-serif';
  try {
    await Promise.all([
      document.fonts.load('700 100px Amiri', name),
      document.fonts.load('400 40px Amiri', 'بسم الله'),
      document.fonts.load('500 40px "IBM Plex Sans Arabic"', 'تُمنح')
    ]);
  } catch (e) {}

  const W = 1754, H = 1240;
  const c = document.createElement('canvas');
  c.width = W; c.height = H;
  const x = c.getContext('2d');
  const PAPER = '#f6faf6', GREEN = '#0f3d36', BRASS = '#a47d1c', INK = '#1c3a34';
  x.direction = 'rtl';
  x.textAlign = 'center';
  x.textBaseline = 'middle';

  x.fillStyle = PAPER; x.fillRect(0, 0, W, H);

  // watermark
  x.save();
  x.globalAlpha = 0.07; x.strokeStyle = BRASS; x.lineWidth = 3;
  star8(x, W / 2, H / 2 + 40, 430); x.stroke();
  x.save(); x.translate(W / 2, H / 2 + 40); x.rotate(Math.PI / 8); x.translate(-W / 2, -(H / 2 + 40));
  star8(x, W / 2, H / 2 + 40, 360); x.stroke(); x.restore();
  x.beginPath(); x.arc(W / 2, H / 2 + 40, 300, 0, Math.PI * 2); x.stroke();
  x.restore();

  // borders
  x.strokeStyle = BRASS; x.lineWidth = 8; x.strokeRect(40, 40, W - 80, H - 80);
  x.strokeStyle = GREEN; x.lineWidth = 2; x.strokeRect(64, 64, W - 128, H - 128);

  // corner stars
  [[64, 64], [W - 64, 64], [64, H - 64], [W - 64, H - 64]].forEach(([cx, cy]) => {
    x.fillStyle = PAPER; x.beginPath(); x.arc(cx, cy, 34, 0, Math.PI * 2); x.fill();
    x.fillStyle = BRASS; star8(x, cx, cy, 30); x.fill();
    x.fillStyle = PAPER; star8(x, cx, cy, 15); x.fill();
  });

  // top emblem
  x.fillStyle = BRASS; star8(x, W / 2, 168, 62); x.fill();
  x.fillStyle = PAPER; star8(x, W / 2, 168, 40); x.fill();
  x.fillStyle = GREEN; x.beginPath(); x.arc(W / 2, 168, 12, 0, Math.PI * 2); x.fill();

  x.fillStyle = INK;
  x.font = '400 46px ' + D;
  x.fillText('بسم الله الرحمن الرحيم', W / 2, 282);

  x.fillStyle = GREEN;
  x.font = '700 150px ' + D;
  x.fillText('شهادة تقدير', W / 2, 415);

  x.fillStyle = BRASS; x.fillRect(W / 2 - 150, 495, 300, 4);

  x.fillStyle = INK;
  x.font = '500 44px ' + B;
  x.fillText('تُمنح هذه الشهادة إلى', W / 2, 565);

  // name, shrink to fit
  let size = 132;
  x.fillStyle = GREEN;
  x.font = '700 ' + size + 'px ' + D;
  while (x.measureText(name).width > W - 420 && size > 48) {
    size -= 4;
    x.font = '700 ' + size + 'px ' + D;
  }
  x.fillText(name, W / 2, 690);
  x.fillStyle = BRASS; x.fillRect(220, 760, W - 440, 2);

  x.fillStyle = INK;
  x.font = '400 42px ' + B;
  x.fillText('تقديرًا لإتمامه مسابقة «نور الإيمان» المكوّنة من ' + n(total) + ' سؤالًا', W / 2, 835);
  x.fillText('وحصوله على ' + n(sc) + ' إجابة صحيحة من ' + n(total) + '، بتقدير: ' + levelOf(sc / total), W / 2, 905);

  x.fillStyle = BRASS;
  x.font = '400 56px ' + D;
  x.fillText('﴿وَقُل رَّبِّ زِدْنِي عِلْمًا﴾', W / 2, 1020);

  x.fillStyle = INK;
  x.font = '400 34px ' + B;
  let dateStr = '';
  try { dateStr = new Date().toLocaleDateString('ar-EG', { year: 'numeric', month: 'long', day: 'numeric' }); } catch (e) {}
  x.fillText('التاريخ: ' + dateStr, W / 2, 1110);

  return c.toDataURL('image/png');
}

