/* ---------- copy phone ---------- */
document.querySelectorAll('.copy-btn').forEach(b => {
  b.addEventListener('click', async () => {
    let ok = false;
    try { await navigator.clipboard.writeText(b.dataset.copy); ok = true; } catch (e) {}
    if (!ok) {
      try {
        const r = document.createRange();
        r.selectNodeContents(b.previousElementSibling);
        const s = window.getSelection();
        s.removeAllRanges();
        s.addRange(r);
      } catch (e) {}
    }
    const old = 'نسخ الرقم';
    b.textContent = ok ? 'تم النسخ' : 'الرقم محدد، انسخه يدويًا';
    setTimeout(() => { b.textContent = old; }, 2200);
  });
});

